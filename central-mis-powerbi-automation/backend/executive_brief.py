import sys
if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')
"""
Central MIS Executive Briefing Generator
Generates the Director's Daily Flash Briefing answering the 10 core questions
from Section 18 of the Organization Automation & MIS Plan.
"""

import os
from datetime import date
import pandas as pd
from backend.database import load_all_tables, get_connection

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXPORTS_DIR = os.path.join(BASE_DIR, "exports")


def generate_director_brief() -> dict:
    """Calculates all key metrics and formats an executive brief for the Managing Director."""
    tables = load_all_tables()
    today_str = date.today().strftime("%B %d, %Y")

    invoices = tables["invoices"]
    expenses = tables["expenses"]
    projects = tables["projects"]
    leads = tables["leads"]
    employees = tables["employees"]
    attendance = tables["attendance"]
    daily_ops = tables["daily_operations"]
    kpis = tables["kpi_master"]
    alerts = tables["alerts_exceptions"]
    departments = tables["departments"]

    # 1. Financial Health
    total_rev = invoices["amount"].sum()
    total_paid = invoices["paid_amount"].sum()
    total_exp = expenses["amount"].sum()
    net_profit = total_rev - total_exp
    margin_pct = (net_profit / total_rev * 100) if total_rev > 0 else 0.0

    overdue_inv = invoices[invoices["status"] == "Overdue"]
    overdue_amt = (overdue_inv["amount"] - overdue_inv["paid_amount"]).sum()
    overdue_count = len(overdue_inv)

    # 2. Project Delivery
    active_prjs = projects[projects["status"].isin(["On Track", "Delayed", "At Risk"])]
    delayed_prjs = projects[projects["status"] == "Delayed"]
    at_risk_prjs = projects[projects["status"] == "At Risk"]
    delayed_count = len(delayed_prjs)
    ontime_rate = ((len(projects) - delayed_count) / len(projects) * 100) if len(projects) > 0 else 100.0

    # 3. CRM & Sales
    open_leads = leads[leads["status"] == "Open"]
    pipeline_val = open_leads["estimated_value"].sum()
    won_leads = leads[leads["stage"] == "Won"]
    conversion_rate = (len(won_leads) / len(leads) * 100) if len(leads) > 0 else 0.0

    # 4. Workforce & Operations
    active_emp_count = len(employees[employees["status"] == "Active"])
    recent_ops = daily_ops.tail(6)
    avg_productivity = recent_ops["productivity_pct"].mean() if not recent_ops.empty else 90.0
    avg_qa = recent_ops["qa_pass_pct"].mean() if not recent_ops.empty else 95.0

    # 5. Critical Alerts
    critical_red = alerts[(alerts["severity"] == "Red") & (alerts["resolution_status"] != "Resolved")]
    amber_alerts = alerts[(alerts["severity"] == "Amber") & (alerts["resolution_status"] != "Resolved")]

    company_status = "RED - IMMEDIATE MANAGEMENT ATTENTION" if len(critical_red) > 0 else ("AMBER - MONITORING REQUIRED" if len(amber_alerts) > 0 else "GREEN - OPTIMAL PERFORMANCE")

    # Generate Markdown text
    md = f"""# 🏢 DIRECTOR'S DAILY MANAGEMENT BRIEFING
**Date**: {today_str}  
**Overall Company Health Status**: `{company_status}`

---

## 1. Executive Summary & Core Financials
- **Total Invoiced Revenue**: ${total_rev:,.2f}
- **Operating Expenses**: ${total_exp:,.2f}
- **Net Operating Profit**: **${net_profit:,.2f}** ({margin_pct:.1f}% Margin)
- **Cash Collected (Paid)**: ${total_paid:,.2f}
- **Overdue Receivables**: **${overdue_amt:,.2f}** across {overdue_count} invoices ⚠️

---

## 2. Critical Exceptions Requiring Director Action (Red Alerts)
"""
    if not critical_red.empty:
        for _, row in critical_red.iterrows():
            md += f"""- **[{row['category'].upper()}] {row['entity_name']}** (Logged: {row['logged_date']}, Delay: {row['delay_days']} days)
  - **Issue**: {row['issue']}
  - **Responsible Owner**: {row['owner']} ({row['responsible_team']})
  - **Required Action**: *{row['action_required']}*
"""
    else:
        md += "- *No Critical Red Exceptions open at this time.*\n"

    md += f"""
---

## 3. Operations & Project Status
- **Active Projects**: {len(active_prjs)} (Delayed: {delayed_count}, At Risk: {len(at_risk_prjs)})
- **On-Time Delivery Rate**: {ontime_rate:.1f}%
- **Average Team Productivity**: {avg_productivity:.1f}%
- **QA First-Pass Yield**: {avg_qa:.1f}%

---

## 4. Sales Pipeline & Commercial Outlook
- **Active Pipeline Value**: **${pipeline_val:,.2f}** ({len(open_leads)} active deals)
- **Lead Conversion Rate**: {conversion_rate:.1f}%
- **Active Workforce Headcount**: {active_emp_count} members across {len(departments)} departments

---
*Report generated by Central MIS Automation Engine.*
"""

    # Write Markdown file
    os.makedirs(EXPORTS_DIR, exist_ok=True)
    brief_md_path = os.path.join(EXPORTS_DIR, "Director_Executive_Brief.md")
    with open(brief_md_path, "w", encoding="utf-8") as f:
        f.write(md.strip() + "\n")

    return {
        "date": today_str,
        "company_status": company_status,
        "revenue": total_rev,
        "net_profit": net_profit,
        "margin_pct": margin_pct,
        "overdue_receivables": overdue_amt,
        "delayed_projects": delayed_count,
        "critical_red_count": len(critical_red),
        "amber_alerts_count": len(amber_alerts),
        "markdown_path": brief_md_path,
        "markdown_content": md
    }


if __name__ == "__main__":
    brief = generate_director_brief()
    print(brief["markdown_content"])
    print(f"\nBriefing saved to: {brief['markdown_path']}")
